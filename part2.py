# ============================================================
# REQUEST WEATHER DATA
# ============================================================

def request_weather(lat, lon):

    params = {

        "latitude": lat,
        "longitude": lon,

        "start_date": START_DATE,
        "end_date": END_DATE,

        "daily": DAILY_STRING,

        "timezone": TIMEZONE,

        "temperature_unit": "celsius",
        "wind_speed_unit": "kmh",
        "precipitation_unit": "mm",

        "models": "era5",

        "cell_selection": "land"
    }

    last_error = None

    for attempt in range(
        1,
        MAX_RETRIES + 1
    ):

        try:

            response = session.get(
                BASE_URL,
                params=params,
                timeout=TIMEOUT
            )

            if response.status_code == 429:

                wait_time = 30 * attempt

                print(
                    f"    Rate limit (429). "
                    f"Waiting {wait_time}s..."
                )

                time.sleep(wait_time)

                continue

            response.raise_for_status()

            data = response.json()

            if data.get("error", False):

                raise RuntimeError(
                    data.get(
                        "reason",
                        "Unknown API error"
                    )
                )

            if "daily" not in data:

                raise RuntimeError(
                    "API response does not contain "
                    "daily data"
                )

            return data

        except Exception as e:

            last_error = e

            print(
                f"    Request failed "
                f"[{attempt}/{MAX_RETRIES}]"
            )

            print(
                "    Error:",
                str(e)[:250]
            )

            if attempt < MAX_RETRIES:

                wait_time = min(
                    15 * attempt,
                    60
                )

                time.sleep(wait_time)

    raise RuntimeError(
        f"API failed after "
        f"{MAX_RETRIES} attempts: "
        f"{last_error}"
    )

# ============================================================
# CONVERT API RESPONSE
# ============================================================

def convert_response(
    data,
    station_id,
    division,
    station,
    district,
    lat,
    lon
):

    daily = data["daily"]

    df = pd.DataFrame(daily)

    if "time" not in df.columns:

        raise ValueError(
            "Date column missing "
            "from API response"
        )

    df.rename(
        columns={
            "time": "Date"
        },
        inplace=True
    )

    df["Date"] = pd.to_datetime(
        df["Date"]
    )

    df["Station_ID"] = station_id
    df["Division"] = division
    df["Station"] = station
    df["District"] = district

    df["Latitude"] = lat
    df["Longitude"] = lon

    if len(df) != EXPECTED_DAYS:

        raise ValueError(
            f"{station}: "
            f"Expected {EXPECTED_DAYS} days, "
            f"got {len(df)}"
        )

    if df["Date"].duplicated().any():

        raise ValueError(
            f"{station}: "
            "Duplicate dates found"
        )

    df = (
        df
        .sort_values("Date")
        .reset_index(drop=True)
    )

    location_cols = [

        "Date",

        "Station_ID",
        "Division",
        "Station",
        "District",

        "Latitude",
        "Longitude"
    ]

    other_cols = [
        col
        for col in df.columns
        if col not in location_cols
    ]

    df = df[
        location_cols +
        other_cols
    ]

    return df

